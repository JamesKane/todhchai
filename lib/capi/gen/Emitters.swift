// abigen's outputs: the C header, and Zig and Odin bindings with the same
// layouts. Each asserts every record's size and field offsets.

let generatedNote = "Generated by abigen from lib/capi/gen/Todhchai.swift; don't edit."

func comment(_ doc: String, _ lead: String, indent: String = "") -> String {
  doc.isEmpty ? "" : doc.split(separator: "\n").map { "\(indent)\(lead) \($0)\n" }.joined()
}

func literal(_ v: Int64, _ t: CType) -> String {
  switch t {
  case .u64 where v < 0: return "0x" + String(UInt64(bitPattern: v), radix: 16)
  default: return String(v)
  }
}

// MARK: C

public func emitC(_ abi: ABI) -> String {
  func ty(_ t: CType) -> String {
    switch t {
    case .void: "void"
    case .bool: "bool"
    case .u8: "uint8_t"
    case .u16: "uint16_t"
    case .u32: "uint32_t"
    case .u64: "uint64_t"
    case .i32: "int32_t"
    case .i64: "int64_t"
    case .f32: "float"
    case .f64: "double"
    case .usize: "size_t"
    case .named(let n): n
    case .opaque(let n): "\(n) *"
    case .pointer(let p, let const): "\(const ? "const " : "")\(ty(p)) *"
    case .cString: "const char *"
    case .array: fatalError("arrays are fields only")
    }
  }
  func decl(_ f: Field) -> String {
    if case .array(let e, let n) = f.type { return "\(ty(e)) \(f.name)[\(n)]" }
    let t = ty(f.type)
    return t.hasSuffix("*") ? "\(t)\(f.name)" : "\(t) \(f.name)"
  }
  func fields(_ r: Record, indent: String) -> String {
    var s = ""
    for f in r.fields {
      if case .named(let n) = f.type, let inner = abi.record(n), inner.anonymousInC {
        s += "\(indent)\(inner.isUnion ? "union" : "struct") {\(inner.doc.isEmpty ? "" : " /* \(inner.doc) */")\n"
        s += fields(inner, indent: indent + "  ")
        s += "\(indent)};\n"
      } else {
        s += "\(indent)\(decl(f));\(f.doc.isEmpty ? "" : " /* \(f.doc) */")\n"
      }
    }
    return s
  }
  let guardName = "TODHCHAI_TODHCHAI_H"
  var s = "// SPDX-License-Identifier: BSD-3-Clause\n// \(generatedNote)\n//\n"
  s += "// libtodhchai's C ABI (docs/sdk.md §12).\n\n"
  s += "#ifndef \(guardName)\n#define \(guardName)\n\n#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
  s += "#ifdef __cplusplus\nextern \"C\" {\n#endif\n"
  var asserts = ""
  for d in abi.decls {
    switch d {
    case .section(let title): s += "\n// MARK: \(title)\n\n"
    case .opaque(let n, let doc): s += comment(doc, "//") + "typedef struct \(n) \(n);\n"
    case .alias(let n, let t, let doc): s += comment(doc, "//") + "typedef \(ty(t)) \(n);\n"
    case .constants(let t, let cs, let doc):
      s += comment(doc, "//")
      for c in cs {
        let v = literal(c.value, t)
        let text = c.value < 0 ? "(\(v))" : (t == .u64 ? "\(v)ull" : (t == .u32 ? "\(v)u" : v))
        s += "#define \(c.name) \(text)\(c.doc.isEmpty ? "" : " /* \(c.doc) */")\n"
      }
    case .record(let r):
      if r.anonymousInC { continue }  // written inside its user
      s += comment(r.doc, "//")
      s += "typedef \(r.isUnion ? "union" : "struct") \(r.name) {\n" + fields(r, indent: "  ") + "} \(r.name);\n"
      asserts += "TD_ABI_ASSERT(sizeof(\(r.name)) == \(abi.recordLayout(r).size), \"\(r.name)\");\n"
      for (name, offset) in abi.offsets(r) {
        if case .named(let n) = r.fields.first(where: { $0.name == name })!.type, abi.record(n)?.anonymousInC == true {
          for inner in abi.record(n)!.fields {
            asserts += "TD_ABI_ASSERT(offsetof(\(r.name), \(inner.name)) == \(offset), \"\(r.name).\(inner.name)\");\n"
          }
        } else {
          asserts += "TD_ABI_ASSERT(offsetof(\(r.name), \(name)) == \(offset), \"\(r.name).\(name)\");\n"
        }
      }
    case .function(let f):
      s += comment(f.doc, "//")
      let params = f.params.isEmpty ? "void" : f.params.map(decl).joined(separator: ", ")
      let r = ty(f.returns)
      s += "\(r)\(r.hasSuffix("*") ? "" : " ")\(f.name)(\(params));\n"
    }
  }
  s += "\n// MARK: Layouts (as abigen computed them)\n\n"
  s += "#ifdef __cplusplus\n#define TD_ABI_ASSERT(e, m) static_assert(e, m)\n#else\n#define TD_ABI_ASSERT(e, m) _Static_assert(e, m)\n#endif\n"
  s += asserts + "#undef TD_ABI_ASSERT\n"
  s += "\n#ifdef __cplusplus\n}\n#endif\n\n#endif\n"
  return s
}

// MARK: Zig

public func emitZig(_ abi: ABI) -> String {
  func typeName(_ n: String) -> String { words(abi.bare(n)).map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined() }
  func ty(_ t: CType, field: Bool = true) -> String {
    switch t {
    case .void: "void"
    case .bool: "bool"
    case .u8: "u8"
    case .u16: "u16"
    case .u32: "u32"
    case .u64: "u64"
    case .i32: "i32"
    case .i64: "i64"
    case .f32: "f32"
    case .f64: "f64"
    case .usize: "usize"
    case .named(let n): typeName(n)
    case .opaque(let n): "?*\(typeName(n))"
    case .pointer(.void, let const): "?*\(const ? "const " : "")anyopaque"
    case .pointer(let p, let const): "[*c]\(const ? "const " : "")\(ty(p))"
    case .cString: "[*c]const u8"
    case .array(let e, let n): "[\(n)]\(ty(e))"
    }
  }
  var s = "// SPDX-License-Identifier: BSD-3-Clause\n// \(generatedNote)\n//\n"
  s += "// libtodhchai for Zig: `const td = @import(\"todhchai.zig\");`, and link\n// with -ltodhchai. Names drop the td_ prefix.\n\n"
  var asserts = ""
  for d in abi.decls {
    switch d {
    case .section(let title): s += "\n// MARK: \(title)\n\n"
    case .opaque(let n, let doc): s += comment(doc, "///") + "pub const \(typeName(n)) = opaque {};\n"
    case .alias(let n, let t, let doc): s += comment(doc, "///") + "pub const \(typeName(n)) = \(ty(t));\n"
    case .constants(let t, let cs, let doc):
      s += comment(doc, "//")
      for c in cs {
        s += comment(c.doc, "///") + "pub const \(abi.bare(c.name)): \(ty(t)) = \(literal(c.value, t));\n"
      }
    case .record(let r):
      let name = typeName(r.name)
      s += comment(r.doc, "///") + "pub const \(name) = extern \(r.isUnion ? "union" : "struct") {\n"
      for f in r.fields { s += comment(f.doc, "///", indent: "    ") + "    \(f.name): \(ty(f.type)),\n" }
      s += "};\n"
      asserts += "    if (@sizeOf(\(name)) != \(abi.recordLayout(r).size)) @compileError(\"\(name) size\");\n"
      for (field, offset) in abi.offsets(r) where !r.isUnion {
        asserts += "    if (@offsetOf(\(name), \"\(field)\") != \(offset)) @compileError(\"\(name).\(field)\");\n"
      }
    case .function(let f):
      let params = f.params.map { "\($0.name): \(ty($0.type))" }.joined(separator: ", ")
      s += comment(f.doc, "///") + "pub extern fn \(f.name)(\(params)) \(ty(f.returns));\n"
      s += "pub const \(abi.bare(f.name)) = \(f.name);\n"
    }
  }
  s += "\n// MARK: Layouts (as abigen computed them)\n\ncomptime {\n" + asserts + "}\n"
  return s
}

// MARK: Odin

public func emitOdin(_ abi: ABI) -> String {
  func typeName(_ n: String) -> String {
    words(abi.bare(n)).map { $0.count <= 3 && $0 == "cpu" ? "CPU" : $0.prefix(1).uppercased() + $0.dropFirst() }
      .joined(separator: "_")
  }
  func ty(_ t: CType) -> String {
    switch t {
    case .void: ""
    case .bool: "bool"
    case .u8: "u8"
    case .u16: "u16"
    case .u32: "u32"
    case .u64: "u64"
    case .i32: "i32"
    case .i64: "i64"
    case .f32: "f32"
    case .f64: "f64"
    case .usize: "uint"
    case .named(let n): typeName(n)
    case .opaque(let n): "^\(typeName(n))"
    case .pointer(.void, _): "rawptr"
    case .pointer(let p, _): "[^]\(ty(p))"
    case .cString: "cstring"
    case .array(let e, let n): "[\(n)]\(ty(e))"
    }
  }
  var s = "// SPDX-License-Identifier: BSD-3-Clause\n// \(generatedNote)\n//\n"
  s += "// libtodhchai for Odin: `import td \"todhchai\"`. Names drop the td_ prefix.\n\npackage todhchai\n\n"
  s += "foreign import lib \"system:todhchai\"\n"
  var asserts = ""
  var procs = ""
  for d in abi.decls {
    switch d {
    case .section(let title): s += "\n// MARK: \(title)\n\n"
    case .opaque(let n, let doc): s += comment(doc, "//") + "\(typeName(n)) :: struct {}\n"
    case .alias(let n, let t, let doc): s += comment(doc, "//") + "\(typeName(n)) :: \(ty(t))\n"
    case .constants(let t, let cs, let doc):
      s += comment(doc, "//")
      for c in cs {
        s += comment(c.doc, "//") + "\(abi.bare(c.name)) :: \(ty(t))(\(literal(c.value, t)))\n"
      }
    case .record(let r):
      let name = typeName(r.name)
      s += comment(r.doc, "//") + "\(name) :: struct\(r.isUnion ? " #raw_union" : "") {\n"
      for f in r.fields {
        let using: Bool
        if case .named(let n) = f.type, abi.record(n)?.anonymousInC == true { using = true } else { using = false }
        s += comment(f.doc, "//", indent: "\t") + "\t\(using ? "using " : "")\(f.name): \(ty(f.type)),\n"
      }
      s += "}\n"
      asserts += "#assert(size_of(\(name)) == \(abi.recordLayout(r).size))\n"
      for (field, offset) in abi.offsets(r) where !r.isUnion {
        asserts += "#assert(offset_of(\(name), \(field)) == \(offset))\n"
      }
    case .function(let f):
      let params = f.params.map { "\($0.name): \(ty($0.type))" }.joined(separator: ", ")
      let ret = f.returns == .void ? "" : " -> \(ty(f.returns))"
      procs += comment(f.doc, "//", indent: "\t") + "\t\(abi.bare(f.name)) :: proc(\(params))\(ret) ---\n"
    }
  }
  s += "\n// MARK: Functions\n\n@(default_calling_convention = \"c\", link_prefix = \"td_\")\nforeign lib {\n" + procs + "}\n"
  s += "\n// MARK: Layouts (as abigen computed them)\n\n" + asserts
  return s
}
