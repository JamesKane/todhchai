// Swift source for Wayland protocols: an object type per interface, its
// requests as methods that encode onto a connection, its events as an enum,
// its enums as types, and one decoder for every event (lib/wayland/runtime
// is what the code calls). Our generator; the output is ours (principle 29).

/// "wl_shm_pool" → "WlShmPool"
func typeName(_ snake: String) -> String {
  snake.split(separator: "_").map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
}

/// "damage_buffer" → "damageBuffer", escaped if a keyword, prefixed if it
/// starts with a digit ("90" → "_90").
func memberName(_ snake: String) -> String {
  let parts = snake.split(separator: "_")
  var name = (parts.first.map(String.init) ?? "") + parts.dropFirst().map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined()
  if let first = name.first, first.isNumber { name = "_" + name }
  return keywords.contains(name) ? "`\(name)`" : name
}

let keywords: Set<String> = [
  "as", "break", "case", "catch", "class", "continue", "default", "defer", "deinit", "do", "else", "enum",
  "extension", "fallthrough", "false", "for", "func", "guard", "if", "import", "in", "init", "inout", "internal",
  "is", "let", "nil", "operator", "private", "protocol", "public", "repeat", "rethrows", "return", "self", "Self",
  "static", "struct", "subscript", "super", "switch", "throw", "throws", "true", "try", "var", "where", "while",
  "Type", "Protocol", "any", "some",
]

public struct SwiftGenerator {
  let protocols: [ProtocolDefinition]
  let interfaces: [String: Interface]

  public init(_ protocols: [ProtocolDefinition]) {
    self.protocols = protocols
    var all: [String: Interface] = [:]
    for p in protocols { for i in p.interfaces { all[i.name] = i } }
    interfaces = all
  }

  /// The type an argument has in Swift.
  func swiftType(_ a: Argument, in interface: Interface) -> String {
    switch a.kind {
    case .int, .uint:
      if let e = a.enumeration { return enumType(e, in: interface) }
      return a.kind == .int ? "Int32" : "UInt32"
    case .fixed: return "WaylandFixed"
    case .string: return a.allowNull ? "String?" : "String"
    case .object:
      let t = a.interface.map(typeName) ?? "UInt32"
      return a.allowNull ? "\(t)?" : t
    case .newID: return a.interface.map(typeName) ?? "UInt32"
    case .array: return "[UInt8]"
    case .fd: return "Int32"
    }
  }

  /// "format" in wl_shm → "WlShm.Format"; "wl_output.transform" → "WlOutput.Transform".
  func enumType(_ ref: String, in interface: Interface) -> String {
    let parts = ref.split(separator: ".")
    if parts.count == 2 { return "\(typeName(String(parts[0]))).\(typeName(String(parts[1])))" }
    return "\(typeName(interface.name)).\(typeName(ref))"
  }

  public func generate(sources: [String]) -> String {
    var out = """
      // SPDX-License-Identifier: BSD-3-Clause
      //
      // Generated by wlgen from \(sources.joined(separator: ", ")).
      // Do not edit; regenerate (CLAUDE.md, "Wayland").

      // swift-format-ignore-file

      """
    let all = protocols.flatMap(\.interfaces)
    out += "\n/// Every interface this code knows.\n"
    out += "public enum WaylandInterface: Sendable, Hashable {\n"
    for i in all { out += "  case \(memberName(i.name))\n" }
    out += "\n  public var name: String {\n    switch self {\n"
    for i in all { out += "    case .\(memberName(i.name)): \"\(i.name)\"\n" }
    out += "    }\n  }\n\n  public var version: UInt32 {\n    switch self {\n"
    for i in all { out += "    case .\(memberName(i.name)): \(i.version)\n" }
    out += "    }\n  }\n}\n"

    for i in all { out += interfaceCode(i) }

    out += "\n/// An event, decoded and typed.\npublic enum WaylandEvent: Sendable {\n"
    for i in all where !i.events.isEmpty {
      out += "  case \(memberName(i.name))(\(typeName(i.name)), \(typeName(i.name)).Event)\n"
    }
    out += "}\n\n"
    out += """
      /// Decodes the event `opcode` of the object `id` (of `interface`).
      public func decodeWaylandEvent(
        _ interface: WaylandInterface, id: UInt32, opcode: UInt16, _ r: inout WaylandReader,
        _ c: WaylandConnection
      ) throws(WaylandError) -> WaylandEvent {
        switch interface {

      """
    for i in all {
      if i.events.isEmpty {
        out += "  case .\(memberName(i.name)): throw .unknownOpcode(\"\(i.name)\", opcode)\n"
      } else {
        out += "  case .\(memberName(i.name)): return .\(memberName(i.name))(\(typeName(i.name))(id: id), try \(typeName(i.name)).Event.decode(opcode, &r, c, parentVersion: c.version(of: id)))\n"
      }
    }
    out += "  }\n}\n"
    return out
  }

  func interfaceCode(_ i: Interface) -> String {
    let t = typeName(i.name)
    var out = """

      // MARK: \(i.name) (version \(i.version))

      public struct \(t): WaylandObject {
        public let id: UInt32
        public init(id: UInt32) { self.id = id }
        public static var interface: WaylandInterface { .\(memberName(i.name)) }
      }

      """
    for e in i.enums { out += enumCode(e, in: t) }
    if !i.requests.isEmpty {
      out += "\nextension \(t) {\n"
      for (opcode, r) in i.requests.enumerated() { out += requestCode(r, opcode: opcode, in: i) }
      out += "}\n"
    }
    if !i.events.isEmpty { out += eventCode(i) }
    return out
  }

  func enumCode(_ e: Enumeration, in t: String) -> String {
    let name = typeName(e.name)
    var out = "\nextension \(t) {\n"
    if e.bitfield {
      out += "  public struct \(name): OptionSet, Hashable, Sendable {\n"
      out += "    public let rawValue: UInt32\n    public init(rawValue: UInt32) { self.rawValue = rawValue }\n"
    } else {
      out += "  public struct \(name): RawRepresentable, Hashable, Sendable {\n"
      out += "    public let rawValue: UInt32\n    public init(rawValue: UInt32) { self.rawValue = rawValue }\n"
    }
    for entry in e.entries {
      out += "    public static let \(memberName(entry.name)) = \(name)(rawValue: \(entry.value))\n"
    }
    out += "  }\n}\n"
    return out
  }

  /// The statement that encodes argument `a`, whose value is `v`.
  func encode(_ a: Argument, _ v: String, in i: Interface) -> String {
    switch a.kind {
    case .int: return a.enumeration == nil ? "m.int(\(v))" : "m.int(Int32(bitPattern: \(v).rawValue))"
    case .uint: return a.enumeration == nil ? "m.uint(\(v))" : "m.uint(\(v).rawValue)"
    case .fixed: return "m.fixed(\(v))"
    case .string: return "m.string(\(v))"
    case .object:
      if a.interface == nil { return "m.uint(\(v))" }
      return a.allowNull ? "m.uint(\(v)?.id ?? 0)" : "m.uint(\(v).id)"
    case .newID: return "m.uint(\(v).id)"
    case .array: return "m.array(\(v))"
    case .fd: return "m.fd(\(v))"
    }
  }

  func requestCode(_ r: Message, opcode: Int, in i: Interface) -> String {
    let newIDs = r.arguments.filter { $0.kind == .newID }
    var parameters = ["_ c: WaylandConnection"]
    var body: [String] = []
    var result = ""
    var generic = ""
    if let n = newIDs.first {
      if let iface = n.interface {
        // A typed new object: it takes this object's version.
        result = " -> \(typeName(iface))"
        body.append("let new = c.newObject(\(typeName(iface)).self, version: c.version(of: id))")
      } else {
        // wl_registry.bind: the caller names the type and version.
        generic = "<T: WaylandObject>"
        parameters.append("_ type: T.Type")
        parameters.append("version: UInt32")
        result = " -> T"
        body.append("let new = c.newObject(T.self, version: version)")
      }
    }
    var encodes: [String] = []
    for a in r.arguments {
      if a.kind == .newID {
        if a.interface == nil {
          encodes.append("m.string(T.interface.name)")
          encodes.append("m.uint(version)")
        }
        encodes.append("m.uint(new.id)")
      } else {
        parameters.append("\(memberName(a.name)): \(swiftType(a, in: i))")
        encodes.append(encode(a, memberName(a.name), in: i))
      }
    }
    body.append("c.send(id, \(opcode)) { m in\n      \(encodes.isEmpty ? "_ = m" : encodes.joined(separator: "\n      "))\n    }")
    if r.isDestructor { body.append("c.forget(id)") }
    if !newIDs.isEmpty { body.append("return new") }
    var code = "  /// \(r.name)" + (r.since > 1 ? ", since version \(r.since)" : "") + (r.isDestructor ? " (destructor)" : "") + ".\n"
    if !result.isEmpty { code += "  @discardableResult\n" }
    code += "  public func \(memberName(r.name))\(generic)(\(parameters.joined(separator: ", ")))\(result) {\n"
    for line in body { code += "    \(line)\n" }
    return code + "  }\n\n"
  }

  /// The expression that decodes argument `a`.
  func decode(_ a: Argument, in i: Interface) -> String {
    switch a.kind {
    case .int:
      return a.enumeration.map { "\(enumType($0, in: i))(rawValue: UInt32(bitPattern: try r.int()))" } ?? "try r.int()"
    case .uint:
      return a.enumeration.map { "\(enumType($0, in: i))(rawValue: try r.uint())" } ?? "try r.uint()"
    case .fixed: return "try r.fixed()"
    case .string: return a.allowNull ? "try r.string()" : "try r.requiredString()"
    case .object:
      guard let iface = a.interface else { return "try r.uint()" }
      return a.allowNull ? "try r.object(\(typeName(iface)).self)" : "try r.requiredObject(\(typeName(iface)).self)"
    case .newID:
      let iface = a.interface.map(typeName) ?? "UInt32"
      return "try r.newObject(\(iface).self, c, version: parentVersion)"
    case .array: return "try r.array()"
    case .fd: return "try r.fd()"
    }
  }

  func eventCode(_ i: Interface) -> String {
    let t = typeName(i.name)
    var out = "\nextension \(t) {\n  public enum Event: Sendable {\n"
    for e in i.events {
      let fields = e.arguments.map { "\(memberName($0.name).replacingOccurrences("`", "")): \(swiftType($0, in: i))" }
      out += "    case \(memberName(e.name))" + (fields.isEmpty ? "" : "(\(fields.joined(separator: ", ")))") + "\n"
    }
    out += "\n    static func decode(_ opcode: UInt16, _ r: inout WaylandReader, _ c: WaylandConnection, parentVersion: UInt32)\n"
    out += "      throws(WaylandError) -> Event\n    {\n      _ = c\n      _ = parentVersion\n      switch opcode {\n"
    for (n, e) in i.events.enumerated() {
      if e.arguments.isEmpty {
        out += "      case \(n): return .\(memberName(e.name))\n"
      } else {
        let lets = e.arguments.enumerated().map { "let a\($0.offset) = \(decode($0.element, in: i))" }
        let labels = e.arguments.enumerated().map { "\(memberName($0.element.name).replacingOccurrences("`", "")): a\($0.offset)" }
        out += "      case \(n):\n        \(lets.joined(separator: "\n        "))\n"
        out += "        return .\(memberName(e.name))(\(labels.joined(separator: ", ")))\n"
      }
    }
    out += "      default: throw .unknownOpcode(\"\(i.name)\", opcode)\n      }\n    }\n  }\n}\n"
    return out
  }
}

extension String {
  func replacingOccurrences(_ target: String, _ replacement: String) -> String {
    split(separator: Character(target), omittingEmptySubsequences: false).joined(separator: replacement)
  }
}
